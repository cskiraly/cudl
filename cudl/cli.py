# The status page: STATUS.md at the main lab's top, rendered from one fragment per worktree (status/<label>.md,
# committed on main) and what cudl knows. The page itself is never committed (see DESIGN, "The status page").
STATUS_DIR = "status"
STATUS_PAGE = "STATUS.md"
PAGE_HEADER = "<!-- generated by cudl from status/*.md and the lab's state: write with `cudl status set`, not here -->"
SECTIONS = ("Running", "Waiting on you", "Next", "Open", "Recently done")  # first, in this order; the rest after
FRAGMENT_RE = re.compile(r"^<!-- cudl: status of (\S+?)(?:, feature id (\S+))? -->$")
STAMP_RE = re.compile(r"^<!-- cudl: (\S+) (\S*) -->$")
FINISHED_SHOWN = 5


def read_fragment(path):
    """(feature id, [[section, time, session, text], …]) of a fragment; (None, []) if there's none."""
    fid, sections, cur = None, [], None
    try:
        text = Path(path).read_text()
    except (OSError, UnicodeDecodeError):
        return None, []
    for line in text.splitlines():
        if line.startswith("## "):
            cur = [line[3:].strip(), "", "", []]
            sections.append(cur)
        elif cur is None:
            m = FRAGMENT_RE.match(line)
            fid = (m.group(2) if m else None) or fid
        elif not cur[1] and not cur[3] and STAMP_RE.match(line):
            cur[1], cur[2] = STAMP_RE.match(line).groups()
        else:
            cur[3].append(line)
    return fid, [[n, t, s, "\n".join(x).strip()] for n, t, s, x in sections]


def fragment_text(label, fid, sections):
    out = [f"<!-- cudl: status of {label}" + (f", feature id {fid}" if fid else "") + " -->"]
    for name, when, sid, text in sections:
        out += ["", f"## {name}", f"<!-- cudl: {when} {sid} -->", text]
    return "\n".join(out) + "\n"


def replace_file(path, text):
    """Write a file by a rename from the lab's git dir, so a reader never sees half of it."""
    gd = git(path.parent, "rev-parse", "--path-format=absolute", "--git-common-dir")
    fd, tmp = tempfile.mkstemp(prefix="cudl-", suffix=".tmp", dir=gd)
    try:
        with os.fdopen(fd, "w") as f:
            f.write(text)
        os.replace(tmp, path)
    except BaseException:
        Path(tmp).unlink(missing_ok=True)
        raise


def page_problem(main):
    """Why cudl won't write the main lab's STATUS.md: one it didn't generate (tracked, or without its header)."""
    page = main.main / STATUS_PAGE
    if git_ok(main.main, "ls-files", "--error-unmatch", "--", STATUS_PAGE):
        return f"{STATUS_PAGE} is tracked"
    if page.is_file() and page.read_text(errors="replace").split("\n", 1)[0] != PAGE_HEADER:
        return f"{STATUS_PAGE} wasn't written by cudl"
    return None


def stamp_time(when):
    return when[:16].replace("T", " ") if when else "?"


def feature_id(main, label):
    return lab_cfg(main, label, "cudlid") if label != "main" else None


def cmd_status(a):
    if a.action:
        return {"set": status_set, "clear": status_clear, "page": status_page}[a.action](a)
    w = Lab.find()
    print(f"{w.label}: {w.top}  [lab branch {head_branch(w.top) or 'detached'}]")
    for r in w.repos().values():
        print("  " + repo_line(w.top, r))
    changes = [l for l in lab_changes(w.top) if not any(l[3:] == r.path for r in w.repos().values())]
    if changes:
        print(f"  lab: {len(changes)} changed")
        for l in changes[:20]:
            print("    " + l)


def write_status(w, label, change, what):
    """Change label's fragment (change(sections) → sections, or None for nothing to do) and commit it
    on main, under the lab lock; a feature's fragment of an earlier feature of the same name starts afresh.
    Returns the commit that had the fragment before (or ""), or None if nothing was done."""
    main = Lab(w.main)
    problem = page_problem(main)
    if problem:
        raise CudlError(f"nothing written: {problem}, so cudl won't replace it. Move it aside first (git mv "
                        f"{STATUS_PAGE} notes/status-before-cudl.md, and commit), then `cudl status set` its sections")
    link_session(w)  # before the lock, which a new linked log takes
    if label != "main":
        adopt_legacy(main)  # a feature from before ids gets one now: one given later would disown this fragment
    rel = f"{STATUS_DIR}/{label}.md"
    with lab_lock(main):
        doing = busy(main.main)
        if doing:
            raise CudlError(f"nothing written: the main lab has {doing} in progress")
        path = main.main / rel
        states = changed_paths(main.main, rel)
        # what a write whose commit failed left (a signing failure): into git before anything replaces it
        earlier = rel in states and commit_selected(main.main, [rel], states, f"status: {label}: as a failed commit left it")
        before = git(main.main, "log", "-1", "--format=%h", "--", rel, check=False)
        fid, sections = read_fragment(path)
        if label != "main" and fid != feature_id(main, label):
            sections = []
        new = change(sections)
        if new is None:
            return before if earlier else None
        if new:
            path.parent.mkdir(exist_ok=True)
            replace_file(path, fragment_text(label, feature_id(main, label), new))
        elif path.exists():
            path.unlink()
        states = changed_paths(main.main, rel)
        if rel in states:
            commit_selected(main.main, [rel], states, f"status: {label}: {what}")
    return before


def status_set(a):
    w = Lab.find()
    section = a.section.strip()
    text = (sys.stdin.read() if a.text == ["-"] else " ".join(a.text)).strip()
    if not section or section.startswith("#"):
        raise CudlError(f"no section named {section!r}")
    if re.search(r"^#{1,2} ", text, re.M):
        raise CudlError("a section's text can't have # or ## headings (the fragment's own): use ### and deeper")
    sid = current_session(w) or ""
    when = datetime.datetime.now().astimezone().isoformat(timespec="seconds")
    replaced = []

    def change(sections):
        hit = next((x for x in sections if x[0].lower() == section.lower()), None)
        if hit and hit[2] != sid:
            replaced.append(list(hit))  # as it was, before it is changed in place
        if not text:
            return [x for x in sections if x is not hit] if hit else None
        if hit:
            hit[1:] = [when, sid, text]
            return sections
        return sections + [[section, when, sid, text]]

    before = write_status(w, w.label, change, section)
    if before is None and not text:
        print(f"{w.label} has no section {section}: nothing removed")
        return
    print(f"status of {w.label}: {section} " + ("written" if text else "removed"))
    for name, t, s, _ in replaced:
        print(f"note: it replaced {name} as " + (f"session {s[:8]}" if s else "someone without a session")
              + f" wrote it at {stamp_time(t)}" + (f" (git show {before}:{STATUS_DIR}/{w.label}.md)" if before else ""))


def status_clear(a):
    w = Lab.find()
    label = a.label or w.label
    if label != "main" and not re.match(r"^[A-Za-z0-9][A-Za-z0-9._-]*$", label):
        raise CudlError(f"{label!r} is not a feature name")
    if label != w.label and (label == "main" or label in w.features()):
        raise CudlError(f"{label} is live: its own sessions clear it (`cudl status clear -f {label}`)")
    gone = write_status(w, label, lambda sections: [] if (w.main / STATUS_DIR / f"{label}.md").exists() else None, "cleared")
    print(f"status of {label}: cleared" if gone is not None else f"no status of {label}")


def status_page(a):
    w = Lab.find()
    if not (w.main / STATUS_DIR).is_dir():
        raise CudlError(f"no {STATUS_DIR}/ in the main lab yet: `cudl status set <section> <text>` starts one")
    render_page(w.main, quiet=False)


def code_facts(top, r):
    d = top / r.path
    if not is_checkout(d):
        return f"{r.name} not checked out"
    b, head, pin = head_branch(d), head_sha(d), pinned(top, r.path)
    s = f"{r.name} {b or 'pinned'} `{short(head)}`" + ("" if pin == head else f" (the lab pins `{short(pin)}`)" if pin
                                                        else " (not pinned)")
    if b:
        base = base_of(d, b, r)
        if b != base and git_ok(d, "rev-parse", "-q", "--verify", base):
            behind, ahead = git(d, "rev-list", "--left-right", "--count", f"{base}...{b}").split()
            s += f", +{ahead}/-{behind} vs {base}"
    return s


def running_sessions(main):
    """[(session, agent, label, since)] of the sessions running (a log without `ended:`): where they started,
    or where a start ran since (a resume in a feature: its linked log there has `running_since:`)."""
    out = {}
    for label in ["main"] + main.features():
        top = main.feature_top(label)
        mine = set(open_sessions(Lab(top)))
        for p in sorted(sessions_dir(top).glob("*.md")):
            fm = readable_frontmatter(p)
            s = fm.get("session")
            if s not in mine or fm.get("feature") != label or fm.get("parent"):
                continue
            if (fm.get("role") != "continued" and s not in out) or fm.get("running_since"):
                out[s] = (s, fm.get("agent") or "?", label, fm.get("running_since") or fm.get("started") or "")
    return list(out.values())


def page_text(main):
    frags = {p.stem: read_fragment(p) for p in sorted((main.main / STATUS_DIR).glob("*.md"))}
    labels = ["main"] + main.features()
    active = {l: frags[l][1] for l in labels if l in frags and (l == "main" or frags[l][0] == feature_id(main, l))}
    stamps = [(t, l, s) for l, secs in active.items() for _, t, s, _ in secs if t]
    lines = [PAGE_HEADER, "# Where we are", "", "Written by cudl from each worktree's status (`status/` in the main lab) "
             "and the lab's state; change it with `cudl status set`, not here."]
    if stamps:
        t, l, s = max(stamps)
        lines += ["", f"Last written: {stamp_time(t)} ({l}" + (f", session {s[:8]}" if s else "") + ")."]
    names = list(SECTIONS) + [n for secs in active.values() for n, *_ in secs]
    for name in dict.fromkeys(n.lower() for n in names):
        blocks = [(l, x) for l in labels for x in active.get(l, []) if x[0].lower() == name]
        if not blocks:
            continue
        lines += ["", f"## {blocks[0][1][0]}"]
        for l, (_, t, s, text) in blocks:
            lines += ["", f"### {l} · {stamp_time(t)}" + (f" · session {s[:8]}" if s else ""), "", text]
    done = sorted(((max((x[1] for x in secs), default=""), l, secs) for l, (_, secs) in frags.items()
                   if l not in active and secs), reverse=True)
    if done:
        lines += ["", "## Finished", ""]
        lines += [f"- {l} ({stamp_time(t)}): {one_line(secs[0][3])}" for t, l, secs in done[:FINISHED_SHOWN]]
        if len(done) > FINISHED_SHOWN:
            lines.append(f"- and {len(done) - FINISHED_SHOWN} more, in {STATUS_DIR}/ (`cudl status clear <name>`)")
    lines += ["", "## Features (cudl)", ""]
    for l in labels:
        top = main.feature_top(l)
        fw = Lab(top)
        parent = lab_parent(main, l) if l != "main" else None
        last = last_session(top, l)
        lines.append(f"- **{l}**" + (f" (stacked on {parent})" if parent else "") + ": "
                     + "; ".join(code_facts(top, r) for r in fw.repos().values())
                     + (f". Last session: {last}" if last else ""))
    running = running_sessions(main)
    lines += ["", "## Sessions running (cudl)", ""]
    lines += [f"- `{s[:8]}` {agent} in {l}, since {stamp_time(since)}" for s, agent, l, since in running] or ["- none"]
    return "\n".join(lines) + "\n"


def render_page(main_top, quiet=True):
    """Write STATUS.md from the fragments and the lab's state, under the lab lock (an older render can't
    replace a newer one), unless the lab has no status/ or a page cudl didn't write."""
    main = Lab(main_top)
    if not (main.main / STATUS_DIR).is_dir():
        return
    with lab_lock(main):
        problem = page_problem(main)
        if problem:
            if not quiet:
                print(f"note: {problem}, so cudl leaves it as it is", file=sys.stderr)
            return
        exclude = common_dir(main) / "info" / "exclude"
        have = exclude.read_text() if exclude.is_file() else ""
        if f"/{STATUS_PAGE}" not in have.splitlines():
            exclude.parent.mkdir(exist_ok=True)
            exclude.write_text(have + ("" if not have or have.endswith("\n") else "\n") + f"/{STATUS_PAGE}\n")
        replace_file(main.main / STATUS_PAGE, page_text(main))
    if not quiet:
        print(f"wrote {main.main / STATUS_PAGE}")


# what may change what the page shows (not `keep`: the lab's git hooks run it inside cudl's own commits,
# which hold the lab lock)
PAGE_COMMANDS = ("add", "new", "take", "commit", "squash", "sync", "finish", "hook")


def page_lab(a):
    """The main lab whose page to write after this command, found before it runs (a finish may remove
    the worktree it runs in); None for a command that changes nothing it shows."""
    if a.cmd == "status" and a.action in ("set", "clear"):
        return lab_main_of()
    if a.cmd not in PAGE_COMMANDS:
        return None
    return lab_main_of(hook_target(hook_input(), a.event) if a.cmd == "hook" else None)


def refresh_page(main_top):
    """After a command that may change what the page shows: never fails the command."""
    if not main_top or not (Path(main_top) / STATUS_DIR).is_dir():
        return
    try:
        render_page(main_top)
    except Exception as e:  # the page is a view; the command did its work
        print(f"cudl: {STATUS_PAGE} not refreshed: {e}", file=sys.stderr)


def cmd_ls(a):
    w = Lab.find()
    for label in ["main"] + w.features():
        top = w.feature_top(label)
        fw = Lab(top)
        changes = [l for l in lab_changes(top) if not any(l[3:] == r.path for r in fw.repos().values())]
        state = f"{len(changes)} changed" if changes else "clean"
        parent = lab_parent(w, label) if label != "main" else None
        pstate = parent_state(w, label) if parent else None
        print(f"{label:<20} {head_branch(top) or 'detached':<24} lab {state}"
              + (f"  ⇐ stacked on {parent}" if parent else "")
              + (f" ({pstate}: `cudl sync -f {label}` to follow the integration branches)" if pstate == "completed" else
                 f" (abandoned: `cudl sync -f {label} --reparent`)" if pstate == "abandoned" else "")
              + ("  (finished, kept)" if label != "main" and feature_finished(w, label) else ""))
        for r in fw.repos().values():
            print("    " + repo_line(top, r))
        last = last_session(top, label)
        if last:
            print(f"    last session: {last}")
    pending = pending_finish(w)
    if pending:
        print(f"\nfinish: {pending}")
    told = pending_notices(w)
    if told:
        print("\nnotices (the next session start shows them):")
        for n in told:
            print(f"  {n.get('time', '?')}: " + str(n.get("text", "")).replace("\n", "\n    "))


ISSUES = "https://github.com/cskiraly/cudl/issues"  # where cudl's maintainers read feedback
ISSUE_LINK_MAX = 6000  # a new-issue link this long still opens in browsers and on GitHub
PRIVATE = "names of your projects, files, hosts or people; paths; anything you wouldn't publish"


def feedback_entry(w, path):
    """A recorded entry, to be read into links: only a file in the main lab's notes/cudl-feedback/, where a
    link points counting. `feedback` runs without asking, so it must not turn other files into links."""
    d = (w.main / "notes" / "cudl-feedback").resolve()
    # relative to the main lab first: a feature's worktree holds older copies of the entries at the same paths
    f = Path(path) if Path(path).is_absolute() or not (w.main / path).exists() else w.main / path
    f = f.resolve()
    if not f.is_file() or f.parent != d or f.suffix != ".md":
        raise CudlError(f"--link {path}: not a feedback entry (a file in the main lab's notes/cudl-feedback/)")
    return f


def issue_links(f):
    """A search of cudl's issues for the entry's title, and a new issue pre-filled with the entry, without
    the line cudl wrote under its title (where and when it was recorded: a feature, a session)."""
    lines = f.read_text().splitlines()
    title = lines[0][2:].strip() if lines and lines[0].startswith("# ") else f.stem
    body = "\n".join(l for l in (lines[1:] if lines and lines[0].startswith("# ") else lines)
                     if not re.match(r"\d{4}-\d{2}-\d{2} \d{2}:\d{2} · from ", l)).strip()
    if title.endswith("…"):  # cut by one_line, inside a word: keep the whole words
        title = title[:-1].rsplit(" ", 1)[0] + "…"
    # a search wants every word: the first few find an issue on the same thing, the whole title only itself
    search = f"{ISSUES}?" + urllib.parse.urlencode({"q": "is:issue " + " ".join(title.rstrip("…").split()[:6])})
    new, cut = f"{ISSUES}/new?" + urllib.parse.urlencode({"title": title, "body": body}), ""
    while len(new) > ISSUE_LINK_MAX and body:
        body, cut = body[:len(body) * 9 // 10], "\n\n(cut here: the rest is in the entry, in the lab)"
        new = f"{ISSUES}/new?" + urllib.parse.urlencode({"title": title, "body": body + cut})
    return search, new


def cmd_feedback(a):
    """A dated note about cudl itself, as its own file in the main lab (no shared file to diverge). Nothing
    is sent: --link prints, for the user, how to pass a cleaned entry on to cudl's maintainers."""
    w = Lab.find()
    if a.link:
        if a.text or a.title:
            raise CudlError("--link prints the links for an entry already recorded: give it no text or --title")
        f = feedback_entry(w, a.link)
        search, new = issue_links(f)
        print(f"For the user, by hand (cudl never sends anything, and an agent never opens these links or "
              f"posts an issue):\n"
              f"  1. make sure {f.relative_to(w.main.resolve())} holds nothing private ({PRIVATE}):\n"
              f"     these links carry its text to GitHub;\n"
              f"  2. search the existing issues, and add to one that already covers it rather than open another:\n"
              f"     {search}\n"
              f"  3. otherwise open this new issue, pre-filled with the entry, check it, and submit it:\n"
              f"     {new}")
        return
    text = " ".join(a.text).strip() or (sys.stdin.read().strip() if not sys.stdin.isatty() else "")
    if not text:
        raise CudlError('what? cudl feedback "<text>"')
    now = datetime.datetime.now().astimezone()
    title = a.title or one_line(text.split("\n")[0], 60)
    slug = re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")[:40] or "note"
    d = w.main / "notes" / "cudl-feedback"
    d.mkdir(parents=True, exist_ok=True)
    sid = current_session(w)
    where = w.label + (f", session {sid}" if sid else "")
    for n in range(1, 1000):
        f = d / (f"{now:%Y-%m-%d-%H%M%S}-{slug}" + (f"-{n}" if n > 1 else "") + ".md")
        try:
            with open(f, "x") as out:  # exclusive: a concurrent or repeated entry gets its own file
                out.write(f"# {title}\n\n{now:%Y-%m-%d %H:%M} · from {where}\n\n{text}\n")
            break
        except FileExistsError:
            continue
    rel = str(f.relative_to(w.main))
    with lab_lock(w):
        git_retry(w.main, "add", "--", rel)
        git_retry(w.main, "commit", "-q", "-m", f"cudl feedback: {title}", "--", rel)
    print(f"recorded {rel} in the main lab. It stays there: cudl never sends anything.\n"
          f"Passing it on to cudl's maintainers is the user's to do, by hand, never an agent's:\n"
          f"  1. edit the file to remove anything private ({PRIVATE});\n"
          f"  2. run `cudl feedback --link {rel}`: it prints a search of the existing issues, to add to one\n"
          f"     that already covers it, and a new issue pre-filled with the entry.")


def cmd_index(a):
    w = Lab.find()
    lines = build_index(w.top)
    print(f"journal/INDEX.md: {len(lines)} sessions")


HOOKS = {
    "session-start": hook_session_start,
    "session-end": hook_session_end,
    "worktree-create": hook_worktree_create,
    "worktree-remove": hook_worktree_remove,
}


def cmd_hook(a):
    if a.event not in HOOKS:  # settings that name an event an older cudl had (pre-compact): exit 2 would
        print(f"cudl: no hook {a.event}, nothing to do", file=sys.stderr)  # block a compaction
        return
    try:
        HOOKS[a.event](a)
    except Exception as e:  # a failing hook must not break the session
        print(f"cudl hook {a.event}: {e}", file=sys.stderr)
        sys.exit(1 if a.event.startswith("worktree") else 0)


# cudl acts on the lab of the working directory, so the copy in a feature of the lab that develops cudl
# (wt/<feature>/code/cudl/bin/cudl) would act on that lab with unfinished code. It doesn't: that lab's
# commands and hooks are its own .cudl/cudl's. It acts on any other lab (scratch labs, the tests').


def own_lab():
    """The main lab in whose feature worktree, under code/, this script is: an unfinished copy."""
    me = Path(__file__).resolve()
    for d in me.parents:
        if (d / MARKER).is_file() and (d / ".git").exists():
            try:
                lab = Lab(d)
            except CudlError:
                return None
            return lab.main if lab.feature and me.is_relative_to(d / "code") else None
    return None


def lab_main_of(start=None):
    try:
        return Lab.find(start).main
    except CudlError:
        return None


def guard_own_lab(a):
    own = own_lab()
    if not own:
        return
    if a.cmd == "install":
        target = own  # it changes the global links, wherever it runs
    elif a.cmd == "init":
        target = own if Path(a.dir).resolve().is_relative_to(own) else None
    elif a.cmd == "upgrade":
        target = lab_main_of(a.dir)
    elif a.cmd == "hook":
        target = lab_main_of(hook_target(hook_input(), a.event))
    else:
        target = lab_main_of()
    if target != own:
        return
    me = Path(__file__).resolve()
    if a.cmd == "ls" or (a.cmd == "status" and not a.action):  # looking only
        print(f"warning: {me} is a feature's unfinished copy of cudl; this lab's own is .cudl/cudl", file=sys.stderr)
        return
    raise CudlError(f"{me} is a feature's unfinished copy of cudl: it doesn't act on {own}, whose commands and "
                    f"hooks are its .cudl/cudl's" + ("" if a.cmd == "install" else
                    f"; try it in a scratch lab: cd <scratch lab> && python3 {me} {a.cmd} …"))


def main(argv=None):
    # no abbreviated options: the agents' permission rules match the command's text (`* --force*`)
    ap = argparse.ArgumentParser(prog="cudl", description=__doc__.split("\n\n")[0], allow_abbrev=False)
    ap.add_argument("-f", "--feature", dest="in_feature", metavar="FEATURE",
                    help="run the command in this feature's worktree (or `main`), from anywhere in the lab")
    sub = ap.add_subparsers(dest="cmd", required=True)
    # the same, after the command: the form the allow rules match (`Bash(.cudl/cudl sync:*)`); its own
    # dest, unset unless given, so a subcommand's default can't overwrite the -f before the command
    here = argparse.ArgumentParser(add_help=False, allow_abbrev=False)
    here.add_argument("-f", "--feature", dest="sub_feature", metavar="FEATURE", default=argparse.SUPPRESS,
                      help="run in this feature's worktree (or `main`), from anywhere in the lab")

    def command(name, here_too=False, **kw):
        return sub.add_parser(name, allow_abbrev=False, parents=[here] if here_too else [], **kw)

    p = command("init", help="create a cudl")
    p.add_argument("dir")
    p.set_defaults(fn=cmd_init)

    p = command("upgrade", help="refresh .cudl/cudl, the skills and an unedited AGENTS.md from the tool "
                       "repository (yours to run: it rewrites the agents' instructions)")
    p.add_argument("dir", nargs="?")
    p.add_argument("--take", action="append", choices=sorted(USER_FILES), help="replace this file with the "
                   "template's even if it was edited (repeatable)")
    p.set_defaults(fn=cmd_upgrade)

    p = command("install", help="link cudl into ~/.local/bin and the cudl skill for Claude Code and Codex")
    p.set_defaults(fn=cmd_install)

    p = command("setup", here_too=True, help="rewrite this worktree's settings.local.json (after a clone or move)")
    p.set_defaults(fn=cmd_setup)

    p = command("add", help="add a code repository as code/<name>")
    p.add_argument("name")
    p.add_argument("url")
    p.add_argument("-b", "--branch", help="integration branch (default: the checked-out one)")
    p.add_argument("--from", dest="from_", help="create the -b branch from this upstream branch "
                   "(e.g. -b lab --from main), so your merges don't land on upstream's branch")
    p.set_defaults(fn=cmd_add)

    p = command("new", help="start a feature: lab and code worktrees under wt/<feature>")
    p.add_argument("feature")
    p.add_argument("-r", "--repo", action="append", help="repo(s) the feature changes (comma list or repeat)")
    p.add_argument("--all", action="store_true", help="branch every repo")
    p.add_argument("--base", action="append", help="<repo>=<branch>: a local branch to start from, sync from and "
                   "finish into, instead of the integration branch")
    p.add_argument("--goal", help="first line of the feature's handoff")
    p.add_argument("--from", dest="from_", help="stack on this feature: start from its lab branch and its code branches")
    p.add_argument("--handoff-from", help="seed the handoff from this feature's handoff, or a file (default with --from: the parent's)")
    p.set_defaults(fn=cmd_new)

    p = command("take", here_too=True, help="in a feature, start a branch in a pinned repo")
    p.add_argument("repo")
    p.add_argument("--base", help="a local branch to sync from and finish into (default: the integration branch)")
    p.set_defaults(fn=cmd_take)

    p = command("status", here_too=True, help="this worktree: repos, branches, changes; set, clear and page: "
                "the main lab's STATUS.md, written from each worktree's status")
    ss = p.add_subparsers(dest="action", metavar="{set,clear,page}")
    q = ss.add_parser("set", parents=[here], allow_abbrev=False, help="replace a section of this worktree's status "
                      "(no text removes it), commit it on main, and write STATUS.md")
    q.add_argument("section", help="Running, Waiting on you, Next, Open, Recently done, or another")
    q.add_argument("text", nargs="*", help="the section's Markdown (`-`: read it from stdin)")
    q = ss.add_parser("clear", parents=[here], allow_abbrev=False, help="remove a worktree's whole status (a finished "
                      "feature's, by name)")
    q.add_argument("label", nargs="?", help="main or a feature (default: this worktree)")
    ss.add_parser("page", parents=[here], allow_abbrev=False, help="write STATUS.md again (after changes made with plain git)")
    p.set_defaults(fn=cmd_status)

    p = command("ls", help="all features")
    p.set_defaults(fn=cmd_ls)

    p = command("commit", here_too=True, help="commit code repos, then the lab with the new pins")
    p.add_argument("-m", "--message", action="append",
                   help="message for all; <repo>=<msg> or lab=<msg> for one (repeatable)")
    p.add_argument("-a", "--all", action="store_true", help="stage modified tracked files in code repos")
    p.add_argument("-A", "--all-files", action="store_true", help="stage everything in code repos, untracked too")
    p.add_argument("--any-branch", action="store_true", help="allow code repos on unexpected branches")
    p.add_argument("--no-memory", action="store_true", help="from a feature, don't commit memory/ on main")
    p.add_argument("--lab", action="append", metavar="PATH", help="stage only these lab paths (repeatable) "
                   "instead of every lab change")
    p.set_defaults(fn=cmd_commit)

    p = command("sync", here_too=True, help="in a feature, merge the integration branches and main's lab in (the parent's, if stacked)")
    p.add_argument("--reparent", action="store_true", help="the parent was abandoned: follow the integration branches instead")
    p.add_argument("--rebase", action="store_true", help="the parent was rewritten (squash, amend, rebase): move this "
                   "feature's own commits onto it (lab commits made again, re-signed, are followed without it)")
    p.add_argument("--force", action="store_true", help="even commits that are on a remote-tracking branch (with "
                   "--rebase, or lab commits made again)")
    p.set_defaults(fn=cmd_sync)

    p = command("finish", help="merge a feature back and remove its worktrees")
    p.add_argument("feature", nargs="?")
    p.add_argument("--stack", metavar="TOP", help="finish TOP and the features it is stacked on, bottom-up, syncing "
                   "each one first; rerun after a stop to go on")
    p.add_argument("--abandon", action="store_true", help="don't merge; keep branches as abandoned/<feature>-<time>")
    p.add_argument("--force", action="store_true", help="with --abandon: discard uncommitted changes")
    p.add_argument("--no-ff", action="store_true", help="merge code branches with a merge commit")
    p.add_argument("--keep", action="store_true", help="merge but keep the worktrees and branches")
    p.set_defaults(fn=cmd_finish)

    p = command("squash", here_too=True, help="in a feature, fold its commits in each owned code repo into one")
    p.add_argument("-r", "--repo", action="append", help="repo(s) to squash (default: every repo the feature owns)")
    p.add_argument("-m", "--message", action="append", help="message for all; <repo>=<msg> or lab=<msg> for one")
    p.add_argument("--force", action="store_true", help="squash even commits already on a remote-tracking branch")
    p.set_defaults(fn=cmd_squash)

    p = command("keep", here_too=True, help="give every commit the lab's history pins a keep ref in its code repo")
    p.add_argument("--check", action="store_true", help="only check; exit 1 if a pin is not kept or lost")
    p.add_argument("--hook", choices=LAB_HOOKS, help=argparse.SUPPRESS)
    p.add_argument("args", nargs="*", help=argparse.SUPPRESS)
    p.set_defaults(fn=cmd_keep)

    p = command("open", help="open a Claude session for a feature (tmux window)")
    p.add_argument("feature")
    p.add_argument("-a", "--agent", choices=sorted(AGENTS), default="claude", help="agent to start (default: claude)")
    p.add_argument("-c", "--command", help="command to run instead of the agent")
    p.add_argument("--print", action="store_true", help="print the command instead")
    p.set_defaults(fn=cmd_open)

    p = command("push", help="push the code repos' integration branches, or a feature's branches with "
                       "--feature (dry run by default; never tags or keep refs; the lab stays local)")
    p.add_argument("--feature", help="push this feature's code branches instead")
    p.add_argument("--remote", help="push to this remote instead of each branch's configured one")
    p.add_argument("--yes", action="store_true")
    p.set_defaults(fn=cmd_push)

    p = command("split", help="move a code repo's artifact history (e.g. notes/) into the lab, pinned to the code it described")
    p.add_argument("repo")
    p.add_argument("--path", action="append", required=True, help="artifact path in the code repo (repeatable)")
    p.add_argument("--rename", action="append", help="OLD=NEW: where an artifact path goes in the lab")
    p.add_argument("--branch", action="append", help="CODE[=LAB]: code branch to import (default: the integration "
                   "branch), as lab branch LAB (default: split/<repo>/<branch>)")
    p.add_argument("--merge", help="imported branch to merge into lab main (default: the integration branch)")
    p.add_argument("--no-merge", action="store_true", help="keep every import as its own lab branch")
    p.add_argument("--dry-run", action="store_true", help="report what would be imported; write nothing")
    p.set_defaults(fn=cmd_split)

    p = command("clean-branch", help="make a copy of a code branch with the artifact paths removed from every commit")
    p.add_argument("repo")
    p.add_argument("branch")
    p.add_argument("--path", action="append", help="artifact path to remove (default: the paths recorded by split)")
    p.add_argument("--as", dest="as_", help="name of the new branch (default: <branch>-clean)")
    p.add_argument("--dry-run", action="store_true", help="report what would change; write nothing")
    p.set_defaults(fn=cmd_clean_branch)

    p = command("import-sessions", help="index Claude Code and Codex sessions from before the lab, as legacy journal entries")
    p.add_argument("path", nargs="+", help="directories the old sessions ran in (worktrees below them are included)")
    p.add_argument("--dry-run", action="store_true", help="list what would be imported")
    p.add_argument("--claude-projects", help="Claude Code projects directory (default: ~/.claude/projects)")
    p.add_argument("--codex-sessions", help="Codex sessions directory (default: ~/.codex/sessions)")
    p.set_defaults(fn=cmd_import_sessions)

    p = command("feedback", here_too=True, help="record a note about cudl itself (a file in the main lab's "
                "notes/cudl-feedback/); nothing is sent: --link prints how you pass a cleaned entry on, by hand")
    p.add_argument("text", nargs="*")
    p.add_argument("--title")
    p.add_argument("--link", metavar="ENTRY", help="for a recorded entry, once you removed anything private from "
                   "it: a search of cudl's issues, and a new issue pre-filled with it, to submit yourself")
    p.set_defaults(fn=cmd_feedback)

    p = command("index", here_too=True, help="rebuild journal/INDEX.md")
    p.set_defaults(fn=cmd_index)

    p = command("hook", help="Claude Code hook entry points")
    p.add_argument("event", help=f"{', '.join(sorted(HOOKS))}; any other does nothing")
    p.add_argument("--agent", choices=sorted(AGENTS), default="claude", help="the agent whose hook this is")
    p.set_defaults(fn=cmd_hook)

    a = ap.parse_args(argv)
    sub_feature = getattr(a, "sub_feature", None)
    if sub_feature and a.in_feature and sub_feature != a.in_feature:
        ap.error(f"-f {a.in_feature} and -f {sub_feature} name different features")
    a.in_feature = a.in_feature or sub_feature
    page = None
    try:
        if a.in_feature:
            top = Lab.find().feature_top(a.in_feature)
            if not top.is_dir():
                raise CudlError(f"-f {a.in_feature}: no such feature")
            os.chdir(top)
        guard_own_lab(a)
        page = page_lab(a)
        a.fn(a)
    except CudlError as e:
        print(f"cudl: {e}", file=sys.stderr)
        sys.exit(1)
    finally:
        refresh_page(page)
