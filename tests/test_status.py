"""End-to-end tests of cudl. The status page: STATUS.md, written from each worktree's status."""

import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))  # helpers.py, however the tests run
from helpers import CudlTest  # noqa: E402


class TestStatus(CudlTest):
    def page(self):
        return (self.w / "STATUS.md").read_text()

    def test_each_worktree_writes_its_own_part(self):
        """main and a feature each set a section: each fragment is committed on main by its path alone,
        and the page, which git ignores, shows both under the one section."""
        self.cudl("new", "f1", "-r", "alpha")
        (self.w / "notes/draft.md").write_text("not the status's to commit\n")
        self.cudl("status", "set", "Running", "the main lab's run")
        self.cudl("status", "set", "-f", "f1", "running", "f1's run")
        self.assertEqual(self.git(self.w, "show", "--name-only", "--format=%s", "HEAD").split("\n"),
                         ["status: f1: running", "", "status/f1.md"])
        self.assertEqual(self.git(self.w, "status", "--porcelain"), "?? notes/draft.md")  # the page: ignored
        page = self.page()
        self.assertTrue(page.startswith("<!-- generated by cudl"))
        self.assertEqual(page.count("## Running"), 1)
        self.assertLess(page.index("### main"), page.index("the main lab's run"))
        self.assertLess(page.index("the main lab's run"), page.index("### f1"))
        self.assertLess(page.index("### f1"), page.index("f1's run"))
        self.assertIn("## Features (cudl)", page)
        self.assertIn("- **f1**: alpha f1", page)

    def test_a_section_is_replaced_and_removed(self):
        self.cudl("status", "set", "Next", "one")
        self.cudl("status", "set", "Open", "a question")
        self.cudl("status", "set", "next", "two", env={"CLAUDE_CODE_SESSION_ID": "5a5a5a5a-0000"})
        fragment = (self.w / "status/main.md").read_text()
        self.assertNotIn("one", fragment)
        self.assertEqual(fragment.count("## Next"), 1)  # the first spelling stays
        self.assertIn("5a5a5a5a-0000", fragment)
        out = self.cudl("status", "set", "Next", "three").stdout  # someone without a session, over 5a5a5a5a
        self.assertIn("it replaced Next as session 5a5a5a5a wrote it", out)
        self.assertIn("git show ", out)
        self.cudl("status", "set", "Next")
        self.assertNotIn("## Next", self.page())
        self.assertIn("a question", self.page())
        self.assertIn("nothing removed", self.cudl("status", "set", "Next").stdout)
        self.cudl("status", "set", "Open")
        self.assertFalse((self.w / "status/main.md").exists())
        self.assertNotIn("status/main.md", self.git(self.w, "ls-files", "status"))

    def test_a_page_cudl_didn_t_write_is_kept(self):
        """A STATUS.md the lab keeps by hand, tracked: status set refuses, writes nothing, and says how to
        move to the fragments."""
        (self.w / "STATUS.md").write_text("# Where we are\n\nmine\n")
        self.git(self.w, "add", "STATUS.md")
        self.git(self.w, "commit", "-q", "-m", "a page of my own")
        head = self.head(self.w)
        p = self.cudl("status", "set", "Running", "x", check=False)
        self.assertNotEqual(p.returncode, 0)
        self.assertIn("STATUS.md is tracked", p.stderr)
        self.assertIn("git mv STATUS.md", p.stderr)
        self.assertEqual(self.head(self.w), head)
        self.assertFalse((self.w / "status").exists())
        self.assertEqual((self.w / "STATUS.md").read_text(), "# Where we are\n\nmine\n")
        # moved aside as it says: then it goes
        self.git(self.w, "mv", "STATUS.md", "notes/status-before-cudl.md")
        self.git(self.w, "commit", "-q", "-m", "the old page, aside")
        self.cudl("status", "set", "Running", "x")
        self.assertIn("x", self.page())
        # an untracked page that isn't cudl's: kept too
        (self.w / "STATUS.md").write_text("by hand\n")
        p = self.cudl("status", "set", "Running", "y", check=False)
        self.assertIn("wasn't written by cudl", p.stderr)
        self.assertEqual((self.w / "STATUS.md").read_text(), "by hand\n")

    def test_the_page_follows_the_lab(self):
        """A commit that moves a pin, a new feature, a session's start: the page shows them after the
        command, with no status written since."""
        self.cudl("status", "set", "Running", "x")
        self.cudl("new", "f1", "-r", "alpha")
        self.assertIn("- **f1**", self.page())
        tip = self.work(self.w / "wt/f1", "alpha", "a1", "1\n", "a one")
        self.assertIn(f"alpha f1 `{tip[:10]}`", self.page())
        sid = "5b5b5b5b-0000-4000-8000-000000000001"
        self.session("session-start", sid, self.w / "wt/f1")
        self.assertIn(f"`{sid[:8]}` claude in f1", self.page())
        self.session("session-end", sid, self.w / "wt/f1")
        self.assertNotIn(sid[:8], self.page().split("## Sessions running")[1])

    def test_a_finished_feature_s_status_goes_to_finished(self):
        """Once its feature is finished, a fragment shows as one line under Finished; a new feature of the
        same name starts with a fragment of its own."""
        self.cudl("new", "f1", "-r", "alpha")
        self.cudl("status", "set", "-f", "f1", "Running", "f1's first run\nmore of it")
        self.work(self.w / "wt/f1", "alpha", "a1", "1\n", "a one")
        self.cudl("finish", "f1")
        page = self.page()
        self.assertNotIn("### f1", page)
        self.assertIn("## Finished", page)
        self.assertIn("- f1 (", page)
        self.assertIn("f1's first run", page.split("## Finished")[1])
        self.cudl("new", "f1", "-r", "beta")
        self.cudl("status", "set", "-f", "f1", "Next", "the second f1")
        fragment = (self.w / "status/f1.md").read_text()
        self.assertNotIn("first run", fragment)
        self.assertIn("### f1", self.page())
        self.cudl("status", "clear", "f1", check=False)  # a live feature's, from elsewhere: refused
        self.assertTrue((self.w / "status/f1.md").exists())
        self.cudl("status", "set", "Next", "main's")
        p = self.cudl("status", "clear", "-f", "f1", "main", check=False)  # and main's from a feature
        self.assertNotEqual(p.returncode, 0)
        self.assertTrue((self.w / "status/main.md").exists())
        self.cudl("status", "clear", "-f", "f1")
        self.assertFalse((self.w / "status/f1.md").exists())

    def test_a_finish_takes_an_uncommitted_fragment(self):
        """A fragment changed and left uncommitted (its commit failed) doesn't stop a finish: the finish's
        checkpoint of main's session files commits it."""
        self.cudl("status", "set", "Running", "x")
        (self.w / "status/main.md").write_text((self.w / "status/main.md").read_text().replace("x", "y"))
        self.cudl("new", "f1", "-r", "alpha")
        self.work(self.w / "wt/f1", "alpha", "a1", "1\n", "a one")
        self.cudl("finish", "f1")
        self.assertIn("y", self.sh("git", "show", "HEAD~1:status/main.md").stdout + self.sh(
            "git", "show", "HEAD:status/main.md").stdout)
        self.assertTrue(self.clean(self.w))

    def test_a_page_that_can_t_be_written_doesn_t_fail_the_command(self):
        self.cudl("status", "set", "Running", "x")
        (self.w / "STATUS.md").unlink()
        (self.w / "STATUS.md").mkdir()  # nothing can replace a directory
        (self.w / "notes/n.md").write_text("n\n")
        p = self.cudl("commit", "-m", "n")
        self.assertIn("STATUS.md not refreshed", p.stderr)
        self.assertEqual(self.git(self.w, "log", "-1", "--format=%s"), "n")

    def test_headings_of_the_fragment_s_own_level_are_refused(self):
        p = self.cudl("status", "set", "Next", "## not a section", check=False)
        self.assertNotEqual(p.returncode, 0)
        self.assertFalse((self.w / "status").exists())
        self.cudl("status", "set", "Next", "-", input="### a sub-heading\n\nis fine\n")
        self.assertIn("### a sub-heading", self.page())


    # --- the code review ---

    def broken_signing(self):
        return {"GIT_CONFIG_COUNT": "3", "GIT_CONFIG_KEY_0": "commit.gpgsign", "GIT_CONFIG_VALUE_0": "true",
                "GIT_CONFIG_KEY_1": "gpg.format", "GIT_CONFIG_VALUE_1": "ssh",
                "GIT_CONFIG_KEY_2": "user.signingkey", "GIT_CONFIG_VALUE_2": str(self.root / "nokey.pub"),
                "SSH_AUTH_SOCK": ""}

    def test_text_whose_commit_failed_is_committed_before_it_is_replaced(self):
        """A set whose commit failed leaves its text uncommitted; the next set commits it first, so what it
        replaces is in git, as the note says (Codex's code review)."""
        self.cudl("status", "set", "Next", "one")
        p = self.cudl("status", "set", "Next", "two, unsigned", check=False, env=self.broken_signing())
        self.assertNotEqual(p.returncode, 0)
        self.cudl("status", "set", "Next", "three")
        self.assertIn("two, unsigned", self.git(self.w, "log", "-p", "--format=", "--", "status/main.md"))
        self.assertTrue(self.clean(self.w))

    def test_a_clear_whose_commit_failed_completes_when_run_again(self):
        self.cudl("status", "set", "Next", "one")
        p = self.cudl("status", "clear", check=False, env=self.broken_signing())
        self.assertNotEqual(p.returncode, 0)
        self.assertIn("cleared", self.cudl("status", "clear").stdout)
        self.assertNotIn("status/main.md", self.git(self.w, "ls-files", "status"))
        self.assertTrue(self.clean(self.w))

    def test_a_feature_from_before_ids_keeps_its_status(self):
        """A feature made before features had ids gets one at its first status, not later at a sync,
        which would have made its fragment look like an earlier namesake's (Codex's code review)."""
        self.cudl("new", "f1", "-r", "alpha")
        self.git(self.w, "config", "--unset", "branch.feat/f1.cudlid")
        self.cudl("status", "set", "-f", "f1", "Next", "the tests")
        self.cudl("sync", "-f", "f1")
        self.assertIn("### f1", self.page())
        self.cudl("status", "set", "-f", "f1", "Open", "a question")
        self.assertIn("the tests", (self.w / "status/f1.md").read_text())

    def test_a_session_resumed_in_a_feature_shows_as_running(self):
        """Ended in main, resumed in a feature: its linked log there is the one running (Codex's code review)."""
        self.cudl("status", "set", "Running", "x")
        self.cudl("new", "f1", "-r", "alpha")
        sid = "5c5c5c5c-0000-4000-8000-000000000001"
        self.session("session-start", sid, self.w)
        self.cudl("commit", "-f", "f1", "-m", "a visit", env={"CLAUDE_CODE_SESSION_ID": sid}, check=False)
        self.session("session-end", sid, self.w)
        self.session("session-start", sid, self.w / "wt/f1")
        self.assertIn(f"`{sid[:8]}` claude in f1", self.page())

    def test_adding_a_repo_shows_on_the_page(self):
        self.cudl("status", "set", "Running", "x")
        self.cudl("add", "gamma", str(self.upstream("gamma", "main")))
        self.assertIn("gamma main", self.page())


if __name__ == "__main__":
    unittest.main()
